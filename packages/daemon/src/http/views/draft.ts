import type { Draft, LintResult } from '@cph/core';
import { html, type SafeHtml } from './html.js';
import { csrfField, platformBadge, platformLabel, routeLabel, statusClass } from './layout.js';
import { renderMarkdown } from './markdown.js';

export const OG_PREVIEW_LINE = "Preview will be generated by LinkedIn from the page's OG tags";

type Json = Record<string, unknown>;
const asObject = (value: unknown): Json => (typeof value === 'object' && value !== null && !Array.isArray(value) ? (value as Json) : {});
const str = (value: unknown): string | undefined => (typeof value === 'string' ? value : undefined);

/** Up to two initials for the feed-post avatar. */
function initials(name: string): string {
  const words = name.replace(/[^\p{L}\p{N}\s]/gu, ' ').trim().split(/\s+/).filter((w) => w !== '');
  const letters = words.slice(0, 2).map((w) => [...w][0] ?? '').join('');
  return letters === '' ? 'in' : letters.toUpperCase();
}

export interface PayloadOptions {
  /** Who the post appears from (the mapped Buffer channel's name, else the account). */
  author?: string;
}

/**
 * The payload exactly as the draft's route will send it:
 * - LinkedIn: the raw text, laid out like a feed post, and a link card only when `payload.link` is
 *   set (it goes out as Buffer's `linkAttachment`); without it LinkedIn builds its own preview from
 *   the page's OG tags.
 * - dev.to: every article field, a rendered look at the markdown, and the raw markdown itself;
 *   Approve & publish sends them to the staged article and makes it public.
 */
export function renderPayload(draft: Draft, options: PayloadOptions = {}): SafeHtml {
  const p = asObject(draft.payload);
  if (draft.platform === 'linkedin') {
    const link = typeof p['link'] === 'object' && p['link'] !== null ? asObject(p['link']) : undefined;
    const author = options.author ?? draft.account;
    return html`<div class="li-post">
<div class="li-head"><span class="li-avatar" aria-hidden="true">${initials(author)}</span><span class="li-who"><strong>${author}</strong><span>LinkedIn post · exact text</span></span></div>
<p class="li-text">${str(p['text']) ?? ''}</p>
${link === undefined
  ? html`<p class="li-foot">${OG_PREVIEW_LINE}.</p>`
  : html`<div class="link-card">
${str(link['thumbnailUrl']) === undefined ? '' : html`<img src="${str(link['thumbnailUrl'])}" alt="" referrerpolicy="no-referrer">`}
<div><strong>${str(link['title']) ?? ''}</strong><br><span class="muted">${str(link['description']) ?? ''}</span><br><code>${str(link['url']) ?? ''}</code></div>
</div>
<p class="li-foot">Sent as the post's link attachment.</p>`}
</div>`;
  }
  if (draft.platform === 'devto') {
    const tagList = Array.isArray(p['tags']) ? (p['tags'] as unknown[]).map(String) : [];
    const body = str(p['body_markdown']) ?? '';
    return html`<div class="devto-preview">
<div class="devto-cover">
<h4>${str(p['title']) ?? ''}</h4>
${tagList.length === 0 ? '' : html`<ul class="devto-tags">${tagList.map((t) => html`<li>${t}</li>`)}</ul>`}
</div>
<div class="md" tabindex="0" role="region" aria-label="Article preview">${renderMarkdown(body)}</div>
</div>
<dl class="facts devto-fields">
<dt>title</dt><dd>${str(p['title']) ?? ''}</dd>
<dt>canonical_url</dt><dd>${str(p['canonical_url']) ?? ''}</dd>
<dt>description</dt><dd>${str(p['description']) ?? ''}</dd>
<dt>tags</dt><dd>${tagList.join(', ')}</dd>
<dt>main_image</dt><dd>${str(p['main_image']) ?? ''}</dd>
${str(p['series']) === undefined ? '' : html`<dt>series</dt><dd>${str(p['series'])}</dd>`}
<dt>published</dt><dd>${draft.remoteRef === undefined ? 'false (not staged yet)' : html`false now; Approve &amp; publish sends these fields to the staged article ${draft.remoteRef} and makes it public`}</dd>
</dl>
<details class="raw"><summary>Raw markdown, exactly as sent</summary>
<pre class="payload">${body}</pre>
</details>`;
  }
  return html`<pre class="payload">${JSON.stringify(draft.payload, null, 2)}</pre>`;
}

export function lintList(lint: LintResult[]): SafeHtml {
  if (lint.length === 0) return html`<p class="chip clean">Lint: clean.</p>`;
  const sorted = [...lint].sort((a, b) => (a.severity === b.severity ? 0 : a.severity === 'error' ? -1 : 1));
  return html`<ul class="lint">${sorted.map(
    (l) => html`<li class="chip ${l.severity}"><span class="sev">${l.severity}</span><span><span class="rule">${l.rule}</span>: ${l.message}</span></li>`,
  )}</ul>`;
}

/** "2 errors · 1 warning" as small chips, or a clean chip. */
export function lintCounts(lint: LintResult[]): SafeHtml {
  const errors = lint.filter((l) => l.severity === 'error').length;
  const warnings = lint.length - errors;
  if (lint.length === 0) return html`<span class="lint-counts"><span class="chip clean">clean</span></span>`;
  return html`<span class="lint-counts">${errors === 0 ? '' : html`<span class="chip error"><span class="sev">${errors} ${errors === 1 ? 'error' : 'errors'}</span></span>`}${warnings === 0 ? '' : html`<span class="chip warning"><span class="sev">${warnings} ${warnings === 1 ? 'warning' : 'warnings'}</span></span>`}</span>`;
}

export interface DraftPageView {
  csrf: string;
  draft: Draft;
  notice?: SafeHtml;
}

/** /drafts/:id: the rendered payload, the lint list and (LinkedIn) the edit box, which PATCHes the draft. */
export function draftSection(view: DraftPageView): SafeHtml {
  const d = view.draft;
  const text = str(asObject(d.payload)['text']);
  return html`<section class="stack" id="draft">
${view.notice ?? ''}
<div class="draft-grid">
<div class="stack">
<article class="card">
<div class="card-head">${platformBadge(d.platform)}<h2>${platformLabel(d.platform)} draft for ${d.slug}</h2><span class="state ${statusClass(d.status)}">${d.status}</span></div>
<h3>Payload</h3>
${renderPayload(d)}
</article>
${d.platform === 'linkedin' && text !== undefined
  ? html`<article class="card">
<h2>Edit</h2>
<form hx-patch="/drafts/${d.id}" hx-target="#draft" hx-swap="outerHTML">
${csrfField(view.csrf)}
<label for="draft-text">Post text</label>
<textarea id="draft-text" name="text" spellcheck="true">${text}</textarea>
<div class="actions"><button type="submit" class="primary">Save</button><span class="save-note">Saving changes the hash and cancels this draft's approvals.</span></div>
</form>
</article>`
  : d.platform === 'devto'
    ? html`<p class="notice info">The dev.to text is the post itself, rendered from the MDX. Edit the post in the site repo to change it.</p>`
    : ''}
</div>
<div class="draft-side">
<article class="card">
<h2>Lint</h2>
${lintList(d.lint)}
</article>
<article class="card">
<h2>Details</h2>
<dl class="facts">
<dt>Status</dt><dd>${d.status}</dd>
<dt>Route</dt><dd>${routeLabel(d.route)}</dd>
<dt>Account</dt><dd>${d.account}</dd>
<dt>Authorship</dt><dd>${d.authorship}</dd>
<dt>Hash</dt><dd><code>${d.payloadSha256}</code></dd>
${d.notBefore === undefined ? '' : html`<dt>Not before</dt><dd>${d.notBefore}</dd>`}
${d.scheduledAt === undefined ? '' : html`<dt>Scheduled</dt><dd>${d.scheduledAt}</dd>`}
${d.remoteRef === undefined ? '' : html`<dt>Staged as</dt><dd>${d.remoteRef}</dd>`}
${d.failureReason === undefined ? '' : html`<dt>Failure</dt><dd>${d.failureReason}</dd>`}
</dl>
</article>
</div>
</div>
</section>`;
}
